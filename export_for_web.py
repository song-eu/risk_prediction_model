"""
export_for_web.py  (로컬에서 실행 — xgboost 필요)
================================================
save_models_mh.py 가 만든 models_saved/<별칭>.json(booster) + registry_mh.json 을
브라우저에서 예측 가능한 단일 web_models.json 으로 변환한다.
브라우저는 XGBoost 를 못 돌리므로, 트리 구조(dump)를 내보내 JS 가 순회한다.

생성물: web_models.json  (predict.html 과 같은 폴더에 두면 됨)

각 질환: label, sex, sigma, base_margin, features, horizons{tau:{iso_x,iso_y}},
         trees(부스터 트리 덤프), verify(자체검증용 예시 입력→예측시간)
"""
import json
from pathlib import Path
import numpy as np
import xgboost as xgb

MODELS = Path("models_saved")
REG = MODELS / "registry.json"          # 다중시점 레지스트리(없으면 registry.json)
OUT = Path("web_models.json")


def base_margin_of(booster):
    """AFT 예측은 exp(base_margin + Σleaf). base_score(margin) 추출."""
    cfg = json.loads(booster.save_config())
    bs = cfg["learner"]["learner_model_param"].get("base_score", "0")
    bs = str(bs).strip().lstrip("[").rstrip("]")
    bs = bs.split(",")[0] 
    # AFT 는 base_score 가 margin(로그시간) 공간. 문자열→float
    return float(bs)


def index_children(node):
    """dump_model JSON 의 children 리스트를 nodeid→노드 dict 로 재구성(JS 순회용)."""
    if "leaf" in node:
        return {"leaf": node["leaf"]}
    ch = {c["nodeid"]: index_children(c) for c in node["children"]}
    return {"split": node["split"], "split_condition": node["split_condition"],
            "yes": node["yes"], "no": node["no"], "missing": node["missing"],
            "children": ch}


def main():
    reg_path = REG if REG.exists() else (MODELS / "registry.json")
    reg = json.loads(reg_path.read_text(encoding="utf-8"))
    out = {"diseases": {}, "note": "generated by export_for_web.py"}

    for key, info in reg.items():
        b = xgb.Booster(); b.load_model(str(MODELS / f"{key}.json"))
        trees_raw = b.get_dump(dump_format="json")
        print(f'b: {b}')
        trees = [index_children(json.loads(t)) for t in trees_raw]
        base_margin = base_margin_of(b)
        feats = info["features"]

        # 시점별 보정: registry_mh(horizons) 또는 단일(iso_x/iso_y→10년)
        if "horizons" in info:
            horizons = {str(int(float(h))): {"iso_x": c["iso_x"], "iso_y": c["iso_y"]}
                        for h, c in info["horizons"].items()}   # "1.0"→"1" 정규화
        else:
            # 단일시점 registry → 세 시점 모두 같은 보정으로 채움(임시)
            iso = {"iso_x": info.get("iso_x") or [0,1], "iso_y": info.get("iso_y") or [0,1]}
            horizons = {"1": iso, "5": iso, "10": iso}

        # 자체검증 예시: 무작위 입력 3개에 대한 booster 예측시간(JS 결과와 대조)
        rng = np.random.default_rng(0)
        verify = []
        for _ in range(3):
            x = {f: float(rng.normal(50, 15)) if "age" in f else float(rng.normal(100, 20))
                 for f in feats}
            dm = xgb.DMatrix(np.array([[x[f] for f in feats]], dtype="float32"),
                             feature_names=feats)
            pt = float(b.predict(dm)[0])
            verify.append({"x": x, "pred_time": pt})

        out["diseases"][key] = {
            "label": info["label"], "sex": info.get("sex", "any"),
            "sigma": float(info["sigma"]), "base_margin": base_margin,
            "features": feats, "horizons": horizons,
            "trees": trees, "verify": verify}
        print(f"[export] {info['label']:<10} trees={len(trees)} feats={len(feats)} "
              f"σ={info['sigma']} base_margin={base_margin:.4f}")

    OUT.write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
    size_mb = OUT.stat().st_size / 1e6
    print(f"\n저장: {OUT.resolve()} ({size_mb:.1f} MB)")
    if size_mb > 20:
        print("⚠ 파일이 큽니다 — 트리 수/깊이가 많으면 웹 로딩이 느릴 수 있음")


if __name__ == "__main__":
    main()
